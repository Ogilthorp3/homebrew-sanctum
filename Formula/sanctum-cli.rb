  def install
    ENV["PIP_NO_INDEX"] = "1"
    ENV["PIP_NO_CACHE_DIR"] = "1"
    ENV["PIP_DISABLE_PIP_VERSION_CHECK"] = "1"
    ENV["OPENSSL_DIR"] = formula_opt_prefix("openssl@3")

    python = formula_opt_bin("python@3.12")/"python3.12"

    build_venv = virtualenv_create(buildpath/"build-venv", python, system_site_packages: false)
    ENV.prepend_path "PYTHONPATH", build_venv.site_packages
    ENV.prepend_path "PYTHONPATH", formula_opt_lib("maturin")/"python3.12/site-packages"

    build_backends = %w[
      flit-core setuptools poetry-core pdm-backend
      packaging pathspec wheel calver cython pkgconfig
      trove-classifiers vcs-versioning tomlkit
      setuptools-scm pluggy hatchling
      hatch-vcs hatch-fancy-pypi-readme expandvars
    ]
    build_backends.each do |name|
      build_venv.pip_install resource(name), build_isolation: false
    end
    ENV.prepend_path "PATH", build_venv.root/"bin"

    venv = virtualenv_create(libexec, python, system_site_packages: false)
    ENV.prepend_path "PYTHONPATH", venv.site_packages

    # Topological install order ensures pycparser -> cffi precede cryptography.
    runtime_deps = %w[
      aiohappyeyeballs
      frozenlist
      typing-extensions
      aiosignal
      attrs
      multidict
      propcache
      idna
      yarl
      aiohttp
      anyio
      distro
      docstring-parser
      certifi
      h11
      httpcore
      httpx
      jiter
      annotated-types
      pydantic-core
      typing-inspection
      pydantic
      sniffio
      anthropic
      pycparser
      cffi
      cryptography
      pyasn1
      pyasn1-modules
      google-auth
      charset-normalizer
      urllib3
      requests
      tenacity
      websockets
      google-genai
      platformdirs
      pyyaml
      mdurl
      markdown-it-py
      pygments
      rich
      annotated-doc
      click
      shellingham
      typer
      websocket-client
    ]
    runtime_deps.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end

    venv.pip_install_and_link buildpath, build_isolation: false
  end

